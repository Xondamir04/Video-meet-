const LANGUAGE_KEY = "videoMeetLanguage";

export function getSavedLanguage(translations) {
  const saved = localStorage.getItem(LANGUAGE_KEY) || "uz";
  return translations[saved] ? saved : "uz";
}

export function saveLanguage(language) {
  localStorage.setItem(LANGUAGE_KEY, language);
}

export function applyDocumentLanguage(language) {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
}
